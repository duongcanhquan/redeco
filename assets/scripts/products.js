// ---------------------------Auto fill---------------------------
function autoFill() {
    let footerItem = localStorage.getItem('footer-item');

    if (footerItem) {
        if (+footerItem < 5) {
            removeActiveClassSilicon();
            silicon?.forEach((item, index) => {
                if (index === +footerItem - 1) {
                    item.classList.add('active');
                }
            });
        } else {
            removeActiveClassOther();
            other?.forEach((item, index) => {
                if (index === +footerItem - 5) {
                    item.classList.add('active');
                }
            });
        }
        switch (+footerItem) {
            case 1:
                siliconImageWrapper.innerHTML =
                    window.innerWidth <= 600
                        ? firstSiliconMobile
                        : firstSilicon;
                break;
            case 2:
                siliconImageWrapper.innerHTML =
                    window.innerWidth <= 600
                        ? secondSiliconMobile
                        : secondSilicon;
                break;
            case 3:
                siliconImageWrapper.innerHTML =
                    window.innerWidth <= 600
                        ? thirdSiliconMobile
                        : thirdSilicon;
                break;
            case 4:
                siliconImageWrapper.innerHTML =
                    window.innerWidth <= 600
                        ? forthSiliconMobile
                        : forthSilicon;
                break;
            case 5:
                otherImageWrapper.innerHTML =
                    window.innerWidth <= 600 ? firstOtherMobile : firstOther;
                break;
            case 6:
                otherImageWrapper.innerHTML =
                    window.innerWidth <= 600 ? secondOtherMobile : secondOther;
                break;
            case 7:
                otherImageWrapper.innerHTML =
                    window.innerWidth <= 600 ? thirdOtherMobile : thirdOther;
                break;
            case 8:
                otherImageWrapper.innerHTML =
                    window.innerWidth <= 600 ? forthOtherMobile : forthOther;
                break;
        }
    }
}

